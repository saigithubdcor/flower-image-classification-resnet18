import os
import numpy as np
import cv2


def load_images_from_folder(folder, size=(256, 256)):
    images = []
    for filename in os.listdir(folder):
        img = cv2.imread(os.path.join(folder, filename))
        if img is not None:
            img = cv2.resize(img, size)
            images.append(img)
    return np.array(images)

train_images_folder = '/content/drive/MyDrive/ProjectTask1/train_data'
val_images_folder = '/content/drive/MyDrive/ProjectTask1/val_data/'

train_images = load_images_from_folder(train_images_folder)
val_images = load_images_from_folder(val_images_folder)

print("Train images shape:", train_images.shape)
print("Validation images shape:", val_images.shape)

train_labels = np.loadtxt('/content/drive/MyDrive/ProjectTask1/train_labels.txt', dtype=int)
val_labels = np.loadtxt('/content/drive/MyDrive/ProjectTask1/val_labels.txt', dtype=int)

print("Train labels shape:", train_labels.shape)
print("Validation labels shape:", val_labels.shape)

from sklearn.decomposition import PCA

train_images_flat = train_images.reshape(train_images.shape[0], -1)
val_images_flat = val_images.reshape(val_images.shape[0], -1)

pca = PCA(n_components=100)
train_images_pca = pca.fit_transform(train_images_flat)
val_images_pca = pca.transform(val_images_flat)

print("Train images after PCA shape:", train_images_pca.shape)
print("Validation images after PCA shape:", val_images_pca.shape)

from tensorflow.keras import layers, models,regularizers
from tensorflow.keras.optimizers import Adam

model = models.Sequential([
    layers.Input(shape=(100,)),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.3),
    layers.BatchNormalization(),

    layers.Dense(61, activation='relu'),
    layers.Dropout(0.25),
    layers.BatchNormalization(),

    layers.Dense(61, activation='softmax')
])

model.compile(optimizer=Adam(learning_rate=0.01),
              loss='sparse_categorical_crossentropy',
              metrics=['accuracy'])

history = model.fit(train_images_pca, train_labels,
                    epochs=25,
                    validation_data=(val_images_pca, val_labels),
                    batch_size=32)

import matplotlib.pyplot as plt

# Summarize history for accuracy
plt.figure(figsize=(12, 6))
plt.subplot(1, 2, 1)
plt.plot(history.history['accuracy'])
plt.plot(history.history['val_accuracy'])
plt.title('Model Accuracy')
plt.ylabel('Accuracy')
plt.xlabel('Epoch')
plt.legend(['Train', 'Validation'], loc='upper left')

# Summarize history for loss
plt.subplot(1, 2, 2)
plt.plot(history.history['loss'])
plt.plot(history.history['val_loss'])
plt.title('Model Loss')
plt.ylabel('Loss')
plt.xlabel('Epoch')
plt.legend(['Train', 'Validation'], loc='upper left')

plt.tight_layout()
plt.show()

